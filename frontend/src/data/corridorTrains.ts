export const getCorridorTrains = (): CorridorTrain[] => {
  return CORRIDOR_TRAINS;
};

export const getTrainByNumber = (trainNumber: string): CorridorTrain | undefined => {
  return CORRIDOR_TRAINS.find((t) => t.train_number === trainNumber);
};

export const getTrainsOnSameRoute = (trainNumber: string): CorridorTrain[] => {
  const target = getTrainByNumber(trainNumber);
  if (!target) return [];
  // Return all other trains running in the same direction along the corridor
  return CORRIDOR_TRAINS.filter(
    (t) => t.direction === target.direction && t.train_number !== target.train_number
  );
};
